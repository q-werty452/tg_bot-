"""
providers/base.py — общий «контракт» для всех ИИ-провайдеров.

Идея: боту всё равно, с кем он разговаривает — с Claude или с GPT.
Он умеет только одно: позвать `provider.ask(...)` и получить текст.
А как именно устроен запрос к конкретному API — забота конкретного класса.

Это называется «абстракция». Плюс: чтобы добавить, например, Gemini,
нужно написать один новый файл и не трогать bot.py.
"""

from abc import ABC, abstractmethod


class LLMProvider(ABC):
    """Базовый класс. Наследники обязаны реализовать ask()."""

    name: str = "base"
    title: str = "Базовый провайдер"

    @abstractmethod
    async def ask(
        self,
        system: str,
        history: list[dict],
        max_tokens: int,
        detailed: bool,
    ) -> str:
        """
        Отправить запрос модели и вернуть текст ответа.

        system     — инструкция «как себя вести» (наш системный промпт).
        history    — вся переписка: [{"role": "user"/"assistant", "content": "..."}],
                     последним элементом идёт свежий вопрос пользователя.
        max_tokens — максимальная длина ответа.
        detailed   — True для развёрнутого режима, False для диалогового.
                     Используется, чтобы включать «размышления» только там,
                     где они реально нужны.
        """
        raise NotImplementedError


class ProviderError(RuntimeError):
    """Понятная человеку ошибка провайдера — её текст можно показать в чате."""
