# ---------------------------------------------------------------------------
# Справочные данные к сообщению жителя
#
# Найденное в справочнике подставляется НЕ в системный промпт, а перед
# последним сообщением жителя. Так системный промпт и начало переписки
# остаются одинаковыми от запроса к запросу, и OpenAI берёт их из своего
# кэша (заметно дешевле), а меняется только хвост. В историю чата эти блоки
# не сохраняются — иначе каждый следующий запрос тащил бы их все заново.
# ---------------------------------------------------------------------------

def compose_user_turn(text: str, *, knowledge: str = "", citizen: str = "") -> str:
    """Сообщение жителя вместе со служебными блоками для модели."""
    parts = []
    if knowledge.strip():
        parts.append("[" + knowledge.strip() + "]")
    if citizen.strip():
        parts.append("[О жителе: " + citizen.strip() + "]")
    if not parts:
        return text
    parts.append("[Сообщение жителя]\n" + text)
    return "\n\n".join(parts)


# ---------------------------------------------------------------------------
# Поиск в интернете
#
# Модель сама решает, что фактов не хватает, и отвечает служебной строкой
# «ПОИСК: запрос» (см. STRICT_RULES). Тогда бот делает второй запрос — уже
# с поиском. Так платный поиск срабатывает только там, где справочник не
# помог, а не на каждое «здравствуйте».
# ---------------------------------------------------------------------------
SEARCH_MARKER = "ПОИСК:"

# Строка-запрос может оказаться не первой (модель иногда пишет «Секунду,
# уточню» и уже потом её) и бывает в звёздочках Markdown. Ищем её в любой
# строке ответа: если служебная строка хоть где-то есть, такой ответ жителю
# показывать нельзя.
_SEARCH_LINE_RE = re.compile(r"^[\s*_>`-]*(?:ПОИСК|SEARCH)\s*:\s*(.*)$",
                             re.IGNORECASE | re.MULTILINE)


def parse_search_request(answer: str) -> str | None:
    """
    Запрос на поиск из ответа модели.

    None — обычный ответ, его можно отдавать жителю. Строка (возможно,
    пустая, если модель забыла написать сам запрос) — модели не хватило
    данных, нужен поиск.
    """
    match = _SEARCH_LINE_RE.search(answer or "")
    if match is None:
        return None
    return match.group(1).strip().strip("*_`«»\"").strip()


