"""
icons.py — единый набор иконок бота и чистка эмодзи из ответов ИИ.

ПОЧЕМУ НЕ SVG
-------------
Текст сообщения в Telegram — это plain text плюс фиксированный набор
«сущностей» (жирный, курсив, код, ссылка, спойлер, цитата). Ни картинок,
ни SVG, ни цвета текста внутри сообщения не существует. Поэтому цветную
векторную иконку в строку вставить нельзя.

Единственное исключение — custom emoji (премиум-эмодзи): это свои картинки,
которые показываются прямо в тексте. Но по документации Bot API их могут
использовать только боты, купившие юзернейм на Fragment, ЛИБО боты, чей
владелец имеет подписку Telegram Premium (в личных чатах и группах).

ЧТО СДЕЛАНО ВМЕСТО ЭТОГО
------------------------
Иконки заданы текстовыми символами Unicode, которые рисуются ТОНКОЙ
КОНТУРНОЙ линией в цвет текста, а не цветными «блобами» системного шрифта.
Такие символы выглядят одинаково аккуратно в светлой и тёмной теме
и не зависят от того, Android у пользователя или iPhone.

Важная деталь — селектор начертания U+FE0E (VS-15). Некоторые символы
(например ⚠) шрифт может нарисовать двумя способами: как текст или как
цветное эмодзи. VS-15 — это команда «рисуй как текст». Обратный ему
U+FE0F (VS-16) — «рисуй как цветное эмодзи»; именно его мы вырезаем
из ответов ИИ.

КАК ВКЛЮЧИТЬ СВОИ ИКОНКИ ПОТОМ
------------------------------
У каждой иконки есть поле emoji_id. Появится Premium — рисуешь свои SVG,
конвертируешь в PNG 100x100, загружаешь ботом как набор custom emoji,
вписываешь сюда полученные id, и включаешь HTML-разметку при отправке
служебных сообщений. Код бота при этом не меняется — он и так спрашивает
иконку по смыслу: ICONS.ok, ICONS.error и так далее.
"""

import re
from dataclasses import dataclass

# Селектор начертания: «этот символ — текст, а не цветное эмодзи».
TEXT = "︎"


@dataclass(frozen=True)
class Icon:
    """Одна иконка: как выглядит сейчас и чем станет, если появится Premium."""

    glyph: str                    # контурный текстовый символ (работает всегда)
    emoji_id: str | None = None   # id custom emoji — пока None у всех
    alt: str = ""                 # запасной символ внутри тега custom emoji

    def __str__(self) -> str:
        """Чтобы иконку можно было просто вставлять в f-строку."""
        return self.glyph

    def to_html(self) -> str:
        """
        Вариант для HTML-разметки. Пока emoji_id не задан, возвращает
        обычный глиф — то есть работает и без Premium.
        """
        if self.emoji_id:
            return f'<tg-emoji emoji-id="{self.emoji_id}">{self.alt or self.glyph}</tg-emoji>'
        return self.glyph


class _Icons:
    """Реестр иконок по смыслу, а не по картинке.

    Код бота пишет ICONS.error, а не конкретный символ. Захочешь сменить
    внешний вид всего бота — правишь только этот класс.
    """

    # Статусы
    ok = Icon("✓")               # U+2713 — тонкая галочка
    error = Icon("✕")            # U+2715 — тонкий крестик
    warning = Icon("⚠" + TEXT)   # U+26A0 + VS-15 — контурный треугольник
    info = Icon("ℹ" + TEXT)      # U+2139 + VS-15

    # Навигация и списки
    arrow = Icon("→")            # U+2192
    bullet = Icon("▸")           # U+25B8
    dot = Icon("·")              # U+00B7

    # Режимы ответа
    mode_detailed = Icon("▤")    # U+25A4 — «лист с текстом»
    mode_chat = Icon("◇")        # U+25C7 — «короткая реплика»

    # Провайдеры (форма намекает на логотип, но остаётся контурной)
    claude = Icon("✳" + TEXT)    # U+2733 — лучи, как у знака Anthropic
    openai = Icon("⬡")           # U+2B21 — контурный шестиугольник
    gemini = Icon("✧")           # U+2727 — четырёхлучевая звезда, как у Gemini
    openrouter = Icon("⌘")       # U+2318 — «перекрёсток», шлюз к разным моделям

    # Действия
    reset = Icon("↺")            # U+21BA
    status = Icon("◎")           # U+25CE
    help = Icon("?")


ICONS = _Icons()


# --------------------------------------------------------------------------
# Чистка ответов ИИ
# --------------------------------------------------------------------------
#
# В промпте мы просим модель не использовать эмодзи, но модели периодически
# всё равно их вставляют. Поэтому вторая линия обороны — фильтр по тексту.
# Осмысленные эмодзи не выбрасываем, а заменяем на наши контурные символы.

_REPLACEMENTS = {
    "✅": ICONS.ok.glyph,
    "✔": ICONS.ok.glyph,
    "☑": ICONS.ok.glyph,
    "❌": ICONS.error.glyph,
    "✖": ICONS.error.glyph,
    "❎": ICONS.error.glyph,
    "⚠": ICONS.warning.glyph,
    "❗": "!",
    "❕": "!",
    "❓": "?",
    "❔": "?",
    "➡": ICONS.arrow.glyph,
    "⬅": "←",
    "▶": ICONS.bullet.glyph,
    "🔸": ICONS.bullet.glyph,
    "🔹": ICONS.bullet.glyph,
    "•": ICONS.dot.glyph,
    "💡": ICONS.info.glyph,
    "ℹ": ICONS.info.glyph,
}

# Символы, которые НЕ трогаем, даже если они попадают в диапазоны эмодзи, —
# это наши собственные иконки.
_KEEP = {icon.glyph.rstrip(TEXT) for icon in vars(_Icons).values() if isinstance(icon, Icon)}
_KEEP |= {"→", "←", "▸", "·"}

# Диапазоны Unicode, в которых живут эмодзи и цветные пиктограммы.
_EMOJI_RANGES = (
    "\U0001F000-\U0001FAFF"  # эмодзи, пиктограммы, флаги, жесты
    "\U00002600-\U000027BF"  # разные символы и дингбаты
    "\U00002B00-\U00002BFF"  # стрелки и геометрия из эмодзи-набора
    "\U0000FE00-\U0000FE0F"  # селекторы начертания
    "\U0000200D"             # zero-width joiner (склейка составных эмодзи)
    "\U000024C2\U00002122\U000000A9\U000000AE"  # Ⓜ ™ © ®
)
_EMOJI_RE = re.compile(f"[{_EMOJI_RANGES}]")

# Замены делаем ОДНИМ проходом через регулярку, а не серией .replace().
# Иначе получается каскад: 💡 меняется на «ℹ︎», а следующая замена «ℹ» уже
# лезет внутрь только что подставленного символа и портит его.
_REPLACE_RE = re.compile("|".join(re.escape(k) for k in _REPLACEMENTS))


def _replace_or_drop(match: re.Match[str]) -> str:
    char = match.group(0)
    if char in _KEEP:
        return char
    if char == TEXT:  # наш собственный селектор «рисуй текстом» — оставляем
        return char
    return ""


def clean_text(text: str) -> str:
    """
    Приводит текст от модели к нашему стилю: заменяет осмысленные эмодзи
    на контурные символы, остальные убирает, подчищает пробелы.
    """
    # 1. Убираем «рисуй цветным» — после этого ✔️ превращается в ✔.
    text = text.replace("️", "")

    # 2. Осмысленные эмодзи меняем на свои иконки (за один проход).
    text = _REPLACE_RE.sub(lambda m: _REPLACEMENTS[m.group(0)], text)

    # 3. Всё остальное эмодзи-содержимое вырезаем.
    text = _EMOJI_RE.sub(_replace_or_drop, text)

    # 4. Подчищаем следы: двойные пробелы и пробелы в конце строк.
    text = re.sub(r"[ \t]{2,}", " ", text)
    text = "\n".join(line.rstrip() for line in text.split("\n"))
    return text.strip()
